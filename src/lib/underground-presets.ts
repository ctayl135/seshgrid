export function applyUndergroundPreset(
  track: Track,
  id: string,
): Partial<Track> {
  const s = UNDERGROUND_PRESETS.find((p) => p.id === id);
  if (!s) throw Error("Unknown underground preset");
  const base = applyTuneStyle(track, s.chain),
    plugins = base.plugins!;
  plugins.pitch = {
    ...plugins.pitch,
    enabled: s.strength > 0,
    strength: s.strength,
    retune: s.retune,
  };
  plugins.chorus = s.chorus;
  return {
    ...base,
    plugins,
    reverb: s.reverb,
    fx: {
      ...trackEffects({ ...track, ...base }),
      drive: s.drive,
      delay: s.delay,
    },
  };
}
